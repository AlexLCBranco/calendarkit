// Round 8 (2.2): writes src/map/basemap.ts, the League map's outline — once, by hand (`npx tsx scripts/make-basemap.ts`);
// nothing here runs in the app or loads anything at runtime.
// Sources (devDependencies, no network): us-atlas 3.0.1 `states-10m.json` (US Census Bureau cartographic boundaries,
// 1:10m) for the lower 48 states + DC; world-atlas 2.0.2 `countries-50m.json` (Natural Earth 1:50m, public domain) for
// Canada and Mexico, drawn as plain neighbouring land. Projection: d3-geo's Albers equal-area conic for the US
// (parallels 29.5° / 45.5°, rotated 96° W), fitted to the lower 48 in a MAP_W-wide box, clipped to the box (so the
// neighbours show only their southern / northern parts). Paths are simplified and rounded to 0.1 unit.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoAlbers, geoPath, type GeoProjection } from 'd3-geo';
import { feature } from 'topojson-client';
import { presimplify, simplify, sphericalTriangleArea } from 'topojson-simplify';
import type { Topology, GeometryCollection } from 'topojson-specification';
import type { Feature, FeatureCollection } from 'geojson';

const require = createRequire(import.meta.url);
const read = (p: string) => JSON.parse(readFileSync(require.resolve(p), 'utf8')) as Topology;

export const MAP_W = 1000;
const PAD = 12;
/** Topology simplification threshold (steradians-ish weight; picked by eye: shapes stay recognisable, file stays small). */
const MIN_WEIGHT = 1e-6;

/** FIPS state code → postal code (lower 48 + DC; 02 AK, 15 HI and the territories are left out of the map). */
const FIPS: Record<string, string> = {
  '01': 'AL', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT', '10': 'DE', '11': 'DC', '12': 'FL', '13': 'GA',
  '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA', '20': 'KS', '21': 'KY', '22': 'LA', '23': 'ME', '24': 'MD', '25': 'MA',
  '26': 'MI', '27': 'MN', '28': 'MS', '29': 'MO', '30': 'MT', '31': 'NE', '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM',
  '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH', '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI', '45': 'SC', '46': 'SD',
  '47': 'TN', '48': 'TX', '49': 'UT', '50': 'VT', '51': 'VA', '53': 'WA', '54': 'WV', '55': 'WI', '56': 'WY',
};

const us = read('us-atlas/states-10m.json');
const usS = simplify(presimplify(us as never, sphericalTriangleArea), MIN_WEIGHT) as Topology;
const states = (feature(usS, us.objects.states as GeometryCollection) as FeatureCollection).features.filter((f) => FIPS[String(f.id)]);
if (states.length !== 49) throw new Error(`expected 48 states + DC, got ${states.length}`);

const world = read('world-atlas/countries-50m.json');
const worldS = simplify(presimplify(world as never, sphericalTriangleArea), MIN_WEIGHT / 4) as Topology;
const countries = (feature(worldS, world.objects.countries as GeometryCollection) as FeatureCollection).features;
const country = (id: string) => countries.find((f) => String(f.id) === id)!;

const projection: GeoProjection = geoAlbers().fitWidth(MAP_W - 2 * PAD, { type: 'FeatureCollection', features: states });
const lower48 = geoPath(projection).bounds({ type: 'FeatureCollection', features: states });
// the box: the lower 48 plus a margin; Toronto (43.64 N) is inside it
const t = projection.translate();
projection.translate([t[0] + PAD - lower48[0][0] + 0, t[1] + PAD - lower48[0][1]]);
const MAP_H = Math.ceil(lower48[1][1] - lower48[0][1] + 2 * PAD);
projection.clipExtent([[0, 0], [MAP_W, MAP_H]]);

const round = (d: string | null) => (d ?? '').replace(/-?\d+\.\d+/g, (n) => String(Math.round(+n)));
const path = geoPath(projection);
const out = {
  states: states.map((f) => [FIPS[String(f.id)]!, round(path(f as Feature))] as const).sort((a, b) => a[0].localeCompare(b[0])),
  canada: round(path(country('124'))),
  mexico: round(path(country('484'))),
};

// The projection as plain numbers for the app (src/map/project.ts): scale k and the offset of d3's raw conic equal-area
// projection after rotation; checked against d3-geo for every arena in tests/map.test.ts.
const k = projection.scale();
const [tx, ty] = projection.translate();
const [cx, cy] = projection.center();
// d3: X = tx + k·(x − x(center)), Y = ty − k·(y − y(center)); with the US preset center [-0.6, 38.7] (after rotation)
const src = `// Generated by scripts/make-basemap.ts (round 8) — do not edit by hand. Lower 48 states + DC: US Census Bureau
// cartographic boundaries via us-atlas 3.0.1 (states-10m). Canada and Mexico: Natural Earth 1:50m via world-atlas 2.0.2
// (public domain). Albers equal-area conic (parallels 29.5° / 45.5°, rotated 96° W), ${MAP_W} × ${MAP_H} units.

export const MAP_W = ${MAP_W};
export const MAP_H = ${MAP_H};
/** d3-geo geoAlbers() as fitted here: scale, translate, center (see src/map/project.ts). */
export const PROJECTION = { k: ${k}, tx: ${tx}, ty: ${ty}, center: [${cx}, ${cy}] as const, parallels: [29.5, 45.5] as const, rotate: -96 };
/** [postal code, SVG path] for each state, by code. */
export const STATES: readonly (readonly [string, string])[] = ${JSON.stringify(out.states)};
export const CANADA = ${JSON.stringify(out.canada)};
export const MEXICO = ${JSON.stringify(out.mexico)};
`;
writeFileSync('src/map/basemap.ts', src);
console.log(`src/map/basemap.ts: ${MAP_W} × ${MAP_H}, ${(src.length / 1024).toFixed(1)} KB`);
